FEM_SPECIAL = {'Ильич': 'Ильинична', 'Кузьмич': 'Кузьминична', 'Никитич': 'Никитична',
               'Саввич': 'Саввична', 'Фомич': 'Фоминична'}
FEM_DOC = {'Йовна': 'Иовна'}  # document already gives a modern-type female patronymic


def modern_name(n):
    return NAMES.get(n, n) if n else n


def modern_patronymic(p):
    """Return (modern, ok). ok=False if the stem is unknown (kept unchanged)."""
    if not p:
        return p, True
    if p in FEM_DOC:
        return FEM_DOC[p], True
    fem = p.endswith('а')
    masc = PATR.get(p[:-1] if fem else p)
    if not masc:
        return p, False
    if not fem:
        return masc, True
    if masc in FEM_SPECIAL:
        return FEM_SPECIAL[masc], True
    return masc[:-2] + 'на', True  # -ович → -овна, -евич → -евна


if __name__ == '__main__':
    import openpyxl
    unknown = set()
    for path in sys.argv[1:]:
        wb = openpyxl.load_workbook(path)
        ws = wb.active
        changed = 0
        for row in ws.iter_rows(min_row=2):
            name, patr = row[1], row[2]
            new_n = modern_name(name.value)
            new_p, ok = modern_patronymic(patr.value)
            if not ok:
                unknown.add(patr.value)
            if new_n != name.value or new_p != patr.value:
                changed += 1
                name.value, patr.value = new_n, new_p
        wb.save(path)
        print(path.rsplit('/', 1)[-1], 'rows changed:', changed)
    if unknown:
        print('UNKNOWN patronymics (kept):', sorted(unknown))
